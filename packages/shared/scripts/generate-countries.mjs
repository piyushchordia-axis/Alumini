// Regenerates src/data/countries.ts: every region libphonenumber-js can dial, with English names from ICU.
// Run from the repo root: node packages/shared/scripts/generate-countries.mjs
// The output is committed so the apps need neither libphonenumber metadata nor Intl.DisplayNames at runtime
// (Hermes on iOS/Android does not ship Intl.DisplayNames).
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(new URL("../../../apps/api/package.json", import.meta.url));
const { getCountries, getCountryCallingCode, Metadata } = require("libphonenumber-js");

const display = new Intl.DisplayNames(["en"], { type: "region" });
// Shorter or more familiar names than ICU's defaults.
const OVERRIDES = {
  HK: "Hong Kong",
  MO: "Macao",
  MM: "Myanmar",
  PS: "Palestine",
  CI: "Côte d'Ivoire",
  CG: "Congo (Republic)",
  CD: "Congo (DRC)",
  AC: "Ascension Island",
  TA: "Tristan da Cunha",
  XK: "Kosovo",
};

/** Product caps: Indian mobiles are 10 digits; libphonenumber's IN possible lengths go up to 13. */
const MAX_NATIONAL_OVERRIDES = { IN: 10 };

const metadata = new Metadata();

function maxNationalDigits(code) {
  if (MAX_NATIONAL_OVERRIDES[code] != null) return MAX_NATIONAL_OVERRIDES[code];
  metadata.selectNumberingPlan(code);
  const lengths = metadata.numberingPlan?.possibleLengths(["mobile"]) ?? metadata.numberingPlan?.possibleLengths() ?? [];
  return lengths[lengths.length - 1] ?? 15;
}

const rows = getCountries()
  .map((code) => ({
    code,
    name: OVERRIDES[code] ?? display.of(code) ?? code,
    dial: `+${getCountryCallingCode(code)}`,
    maxNationalDigits: maxNationalDigits(code),
  }))
  .filter((c) => c.name && c.name !== c.code);
rows.sort((a, b) => (a.code === "IN" ? -1 : b.code === "IN" ? 1 : a.name.localeCompare(b.name, "en")));

const body = rows
  .map((c) => `  { code: ${JSON.stringify(c.code)}, name: ${JSON.stringify(c.name)}, dial: ${JSON.stringify(c.dial)}, maxNationalDigits: ${c.maxNationalDigits} },`)
  .join("\n");
const out = `// Generated by packages/shared/scripts/generate-countries.mjs. Do not edit by hand.
export interface Country {
  /** ISO 3166-1 alpha-2 (plus a few dialable territories such as AC and XK). */
  code: string;
  name: string;
  /** International calling code, e.g. "+91". Several countries share one (US, CA and others use +1). */
  dial: string;
  /** Max national significant digits for the number field (spaces/hyphens not counted). India is capped at 10. */
  maxNationalDigits: number;
}

/** India first, then alphabetical by English name. */
export const COUNTRIES: readonly Country[] = [
${body}
];
`;
writeFileSync(new URL("../src/data/countries.ts", import.meta.url), out);
console.log(`Wrote ${rows.length} countries`);
